// Optional asset-generation tool; the firmware builds from the committed C asset.
// Requires Node.js and the sharp package. Run: node scripts/generate_wordmark.cjs
const fs = require('node:fs');
const path = require('node:path');
const sharp = require('sharp');

(async () => {
  const root = path.resolve(__dirname, '..');
  const source = path.join(root, 'assets/branding/solominer-wordmark.svg');
  // Match the approved mockup: 82% of the native 410px display width.
  // Fit without stretching, and preserve alpha for the static stars behind it.
  const { data, info } = await sharp(source, { density: 288 })
    .resize(336, 36, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  if (info.channels !== 4) throw new Error('Expected RGBA data');
  const bgra = Buffer.alloc(data.length);
  for (let i = 0; i < data.length; i += 4) {
    bgra[i] = data[i + 2]; bgra[i + 1] = data[i + 1];
    bgra[i + 2] = data[i]; bgra[i + 3] = data[i + 3];
  }
  const rows = [];
  for (let i = 0; i < bgra.length; i += 24)
    rows.push('    ' + Array.from(bgra.subarray(i, i + 24), b => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ',');
  const generated = `// Generated by scripts/generate_wordmark.cjs from the official SOLOMINER SVG.
// BGRA bytes encode LVGL ARGB8888 on the little-endian ESP32-S3.
#include "solominer_wordmark.h"

static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t wordmark_pixels[] = {
${rows.join('\n')}
};

const lv_image_dsc_t solominer_wordmark = {
    .header = {
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_ARGB8888,
        .flags = 0,
        .w = ${info.width},
        .h = ${info.height},
        .stride = ${info.width * 4},
    },
    .data_size = sizeof(wordmark_pixels),
    .data = wordmark_pixels,
};
`;
  fs.writeFileSync(path.join(root, 'src/drivers/displays/solominer_wordmark.c'), generated);
  console.log(`Generated transparent wordmark: ${info.width} × ${info.height}, ${data.length} bytes.`);
})().catch(error => { console.error(error.message); process.exitCode = 1; });
