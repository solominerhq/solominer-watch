#!/usr/bin/env python3
"""Reproduce current LVGL image bytes from committed PNG sources (requires Pillow)."""
from pathlib import Path
import argparse,re,struct
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]

def pixels(image,fmt):
    if fmt=='A8':return image.convert('L').tobytes()
    rgb=bytearray();alpha=bytearray()
    for red,green,blue,a in image.convert('RGBA').getdata():
        rgb+=struct.pack('<H',((red>>3)<<11)|((green>>2)<<5)|(blue>>3));alpha.append(a)
    return bytes(rgb+alpha)

def array(text,name):
    raw=text.split(name+'[] = {')[1].split('};')[0]
    return bytes(int(x,16) for x in re.findall(r'0x([0-9a-fA-F]{2})',raw))

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    folder=ROOT/'assets/celebration';target=ROOT/'src/drivers/displays/block_found_assets.c';old=target.read_text()
    source=Image.open(folder/'astronaut-poses.png')
    images=[('mission_moon',Image.open(folder/'moon-transparent-20261020.png').resize((410,502),Image.Resampling.LANCZOS).crop((0,350,410,502)),'RGB565A8')]
    for index,(x,y,w,h) in [(0,(42,24,480,461)),(1,(580,48,464,454)),(3,(63,512,438,478)),(4,(528,540,500,451)),(5,(1072,525,450,472))]:
        im=source.crop((x,y,x+w,y+h)).resize((round(w*.56),round(h*.56)),Image.Resampling.LANCZOS)
        images.append(('mission_pose_'+str(index),im,'RGB565A8'))
    for name in ('mission_block','mission_found'):images.append((name,Image.open(folder/(name+'.png')),'A8'))
    parts=['#include "block_found_assets.h"\n// Source: assets/celebration; generated by scripts/generate_artwork.py.\n']
    for name,im,fmt in images:
        data=pixels(im,fmt);w,h=im.size
        if args.check:
            if data!=array(old,name+'_pixels'):raise SystemExit('Image bytes differ: '+name)
        else:
            parts.append('static const LV_ATTRIBUTE_MEM_ALIGN uint8_t '+name+'_pixels[] = {\n'+''.join(' '+','.join('0x%02x'%v for v in data[i:i+32])+',\n' for i in range(0,len(data),32))+'};\n')
            parts.append('const lv_image_dsc_t '+name+' = { .header={.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_'+fmt+',.flags=0,.w='+str(w)+',.h='+str(h)+',.stride='+str(w if fmt=='A8' else w*2)+'},.data_size=sizeof('+name+'_pixels),.data='+name+'_pixels };\n')
        print(('Verified ' if args.check else 'Generated ')+name)
    if not args.check:target.write_text(''.join(parts))
    # The splash PNG preserves the 200 x 200 alpha-matted source bitmap.
    splash=Image.open(ROOT/'assets/splash/astronaut.png').convert('RGBA').tobytes('raw','BGRA')
    dest=ROOT/'src/drivers/displays/Astronaut_200x200.c';text=dest.read_text()
    if args.check:
        if splash!=array(text,'Astronaut_200x200_map'):raise SystemExit('Splash bytes differ')
    else:
        start=text.index('Astronaut_200x200_map[] = {')+len('Astronaut_200x200_map[] = {');end=text.index('};',start)
        body='\n'+''.join(' '+','.join('0x%02x'%v for v in splash[i:i+32])+',\n' for i in range(0,len(splash),32))
        dest.write_text(text[:start]+body+text[end:])
    print('Verified splash' if args.check else 'Generated splash')
if __name__=='__main__':main()
