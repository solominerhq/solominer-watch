#!/usr/bin/env python3
"""Build a reproducible, offline-only setup page into a flash-resident asset."""
from pathlib import Path
import gzip, hashlib
ROOT=Path(__file__).resolve().parents[1]
folder=ROOT/'assets/setup-portal'
html=(folder/'index.html').read_text().replace('/* PORTAL_CSS */',(folder/'portal.css').read_text()).replace('/* PORTAL_JS */',(folder/'portal.js').read_text())
assert '/* PORTAL_' not in html
payload=gzip.compress(html.encode(),compresslevel=9,mtime=0)
lines=['// Generated by scripts/build_setup_portal.py; edit assets/setup-portal instead.', '#pragma once','#include <Arduino.h>','namespace setup_portal {','static const uint8_t htmlGzip[] PROGMEM = {']
lines += ['    '+','.join('0x%02x'%b for b in payload[i:i+24])+',' for i in range(0,len(payload),24)]
lines += ['};','}']
(ROOT/'src/network/setup_portal_asset.h').write_text('\n'.join(lines)+'\n')
print('Setup portal:',len(html.encode()),'bytes HTML;',len(payload),'bytes gzip;',hashlib.sha256(payload).hexdigest())
